// Build sprites from art/**/*.txt: npm run assets (or: npx tsx tools/build-sprites.ts)
//   src/assets/generated/sprites.ts   palette and frame data for the game
//   build/<name>.png                  raw sheet: 8 px cells, one row per animation, no outline
//   docs/contact-sheet.png            every frame, outlined, plus the palette, at 6x (used in ART_STYLE.md)
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Raster, type RGBA } from "./lib/raster.ts";
import { buildSpriteData, loadPalette, outlinedImage, rawImage } from "./lib/sprites.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const BG: RGBA = [34, 32, 44, 255];
const SHEET_SCALE = 6;

const data = buildSpriteData(ROOT);
const pal = loadPalette(ROOT);

mkdirSync(join(ROOT, "src", "assets", "generated"), { recursive: true });
writeFileSync(
  join(ROOT, "src", "assets", "generated", "sprites.ts"),
  "// Generated by tools/build-sprites.ts from art/ and palette/. Do not edit.\n" +
    'import type { SpriteData } from "../types.ts";\n\n' +
    `export const SPRITES: SpriteData = ${JSON.stringify(data)};\n`,
);

// Raw sheets, one per sprite.
mkdirSync(join(ROOT, "build"), { recursive: true });
for (const [name, def] of Object.entries(data.sprites)) {
  const anims = Object.values(def.anims);
  const width = Math.max(...anims.map(a => a.frames.reduce((w, f) => w + f[0]!.length, 0)));
  const heights = anims.map(a => Math.max(...a.frames.map(f => f.length)));
  const sheet = new Raster(width, heights.reduce((a, b) => a + b, 0));
  anims.forEach((a, r) => {
    let x = 0;
    const y = heights.slice(0, r).reduce((s, h) => s + h, 0);
    for (const f of a.frames) { sheet.paste(rawImage(f, pal), x, y); x += f[0]!.length; }
  });
  sheet.savePng(join(ROOT, "build", `${name}.png`));
}

// Contact sheet: one row per animation (outlined, tiles raw), then the palette swatches.
const rows = Object.values(data.sprites).flatMap(def =>
  Object.values(def.anims).map(a => a.frames.map(f => (def.kind === "tile" ? rawImage(f, pal) : outlinedImage(f, pal)))));
const swatches = Object.keys(pal.rgba).filter(c => !pal.noOutline.has(c));
const width = Math.max(Math.max(...rows.map(r => r.reduce((w, i) => w + i.width + 2, 0))), swatches.length * 6) + 2;
const rowH = rows.map(r => Math.max(...r.map(i => i.height)) + 2);
const contact = new Raster(width, rowH.reduce((a, b) => a + b, 0) + 10, BG);
let y = 2;
rows.forEach((ims, r) => {
  let x = 2;
  for (const im of ims) { contact.composite(im, x, y); x += im.width + 2; }
  y += rowH[r]!;
});
swatches.forEach((c, i) => {
  for (let dy = 0; dy < 5; dy++) for (let dx = 0; dx < 5; dx++) contact.set(2 + i * 6 + dx, y + dy, pal.rgba[c]!);
});
mkdirSync(join(ROOT, "docs"), { recursive: true });
contact.scale(SHEET_SCALE).savePng(join(ROOT, "docs", "contact-sheet.png"));

console.log(`Built ${Object.keys(data.sprites).length} sprites`);
