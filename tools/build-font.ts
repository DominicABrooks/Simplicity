// Build the Simplicity Pixel font: npm run assets (or: npx tsx tools/build-font.ts)
//   public/fonts/simplicity-pixel.ttf   for page text
//   src/assets/generated/font.ts        the same glyphs for text drawn on canvas
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { buildTtf, fontTable, loadGlyphs } from "./lib/font.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const glyphs = loadGlyphs(ROOT);
const ttf = buildTtf(glyphs);

mkdirSync(join(ROOT, "public", "fonts"), { recursive: true });
writeFileSync(join(ROOT, "public", "fonts", "simplicity-pixel.ttf"), ttf);
mkdirSync(join(ROOT, "src", "assets", "generated"), { recursive: true });
writeFileSync(
  join(ROOT, "src", "assets", "generated", "font.ts"),
  "// Generated by tools/build-font.ts from font/pixel.txt. Do not edit.\n" +
    'import type { PixelFont } from "../types.ts";\n\n' +
    `export const PIXEL_FONT: PixelFont = ${JSON.stringify(fontTable(glyphs))};\n`,
);
console.log(`Built Simplicity Pixel: ${glyphs.length} glyphs, ${ttf.length} bytes`);
